// Builds data/words.js from the ENABLE1 word list (public domain).
// Usage: node scripts/build-wordlist.mjs [path-or-url]
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT_URL = 'https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt';
const MIN_LEN = 3;
const MAX_LEN = 12;

const src = process.argv[2] || DEFAULT_URL;
const text = /^https?:/.test(src) ? await (await fetch(src)).text() : await readFile(src, 'utf8');

const words = text
  .split(/\r?\n/)
  .map((w) => w.trim().toLowerCase())
  .filter((w) => /^[a-z]+$/.test(w) && w.length >= MIN_LEN && w.length <= MAX_LEN);

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'data', 'words.js');
await mkdir(dirname(out), { recursive: true });
await writeFile(
  out,
  '// Generated by scripts/build-wordlist.mjs from ENABLE1 (public domain). Do not edit.\n' +
    '(function (root) {\n' +
    '  const ST = (root.ST = root.ST || {});\n' +
    `  ST.WORDS = ${JSON.stringify(words.join('\n'))};\n` +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = ST;\n" +
    "})(typeof window !== 'undefined' ? window : globalThis);\n"
);
console.log(`Wrote ${words.length} words to ${out}`);
